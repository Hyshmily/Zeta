package io.github.hyshmily.zeta.annotation;

import io.github.hyshmily.zeta.cache.cachesupport.policy.PutPolicy;
import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Declares a write-through cache on the annotated method — the declarative form
 * of {@link io.github.hyshmily.zeta.Zeta#put(String, Object, PutPolicy)}.
 *
 * <p>
 * The body runs first; its non-{@code null} return value is then written
 * under {@code cache + '\u0000' + key}. A {@code void}/{@code Void} method is
 * rejected when the bean is proxied because it can never produce a value; a
 * non-void method returning {@code null} writes nothing — {@code null} is never
 * cached.
 *
 * <p>
 * <b>Pre-body vs post-body resolution.</b> A key expression that does not
 * read {@code #result} is resolved before the body runs, so a null argument or
 * a null key fails before the business side effect. A synced dynamic hard TTL
 * is also evaluated before the body, because a permanent value cannot be
 * broadcast; the evaluated value is reused by the write. Every other TTL is
 * evaluated after the body, once the result is known to be non-null and not
 * vetoed by {@link #unless()}. That is what makes {@code key = "#result.id"}
 * work for an entity whose id is generated by the body (a database
 * auto-increment, a UUID minted inside the method).
 *
 * <p>
 * {@link #sync()} selects whether the write converges across instances
 * through the message channel. The default is {@code true}: a write is an
 * author's decision and peers should hear about it. Set it to {@code false}
 * only for data that is genuinely instance-local — the entry then stays stale
 * on peers until its hard TTL expires.
 *
 * <p>
 * Only a normal return is written — a body that throws writes nothing. The
 * write happens after the body completed; with the default advice ordering the
 * transaction interceptor sits inside the cache advice, so the transaction has
 * already committed by then, and a custom order that places the transaction
 * outside makes the facade defer the write to after-commit. Either way a
 * rolled-back write is never cached.
 *
 * <p>
 * <b>One verb per method</b> — see {@link ZetaCached}.
 *
 * <pre>{@code
 * @ZetaPut(cache = "users", key = "#user.id")
 * User save(User user) {
 *   return repository.save(user);
 * }
 *
 * @ZetaPut(cache = "users", key = "#result.id", unless = "#result.status != 'ACTIVE'")
 * User create(User user) {
 *   return repository.insert(user);
 * }
 * }</pre>
 */
@Target(ElementType.METHOD)
@Retention(RetentionPolicy.RUNTIME)
@Documented
public @interface ZetaPut {
  /**
   * The cache namespace, required (same encoding as {@link ZetaCached#cache()}).
   *
   * @return the namespace
   */
  String cache();

  /**
   * SpEL expression resolving the logical key, evaluated once per call. The
   * arguments are bound as {@code #p0}/{@code #a0} and by parameter name,
   * {@code #root.*} is bound as on a read, and {@code #result} holds the
   * returned value. An expression that does not read {@code #result} is
   * resolved before the body; one that does is resolved after it returns. Empty
   * means the default key — see {@link ZetaCached#key()}.
   *
   * @return the key expression, or empty for the default key
   */
  String key() default "";

  /**
   * SpEL expression deciding whether this non-{@code null} result is written,
   * evaluated once after the body returned with {@code #result} bound.
   * {@code true} returns the value to the caller but writes no entry — the
   * write-side counterpart of {@link ZetaCached#unless()}.
   *
   * <p>
   * An expression that throws at evaluation time fails open (the value is
   * written) and logs at DEBUG, because a broken veto must not silently stop every
   * write and must not become a per-call WARN storm; a malformed expression fails
   * startup instead.
   *
   * @return the write veto expression, or empty for "always write"
   */
  String unless() default "";

  /**
   * Hard TTL override for the entry this write creates: a literal millisecond
   * count or a SpEL expression (with {@code #result} bound when it reads it —
   * see {@link #key()}). Empty or {@code "0"} means the configured default. A
   * malformed expression, a digits-only literal outside the {@code long} range,
   * or an unknown SpEL variable (when parameter names are discoverable) fails
   * startup; a runtime evaluation failure degrades to the default. Supports
   * {@code ${...}} placeholders. A permanent
   * entry ({@code Long.MAX_VALUE}) cannot be synced; for a synced write, a
   * dynamic hard TTL that does not depend on {@code #result} is checked before
   * the body.
   *
   * @return the hard TTL literal or expression
   */
  String hardTtl() default "";

  /**
   * Soft TTL override for the entry this write creates, same rule as
   * {@link #hardTtl()}.
   *
   * @return the soft TTL literal or expression
   */
  String softTtl() default "";

  /**
   * Whether this write is broadcast to peer instances. {@code true} (default)
   * makes peers apply the value without reloading; {@code false} leaves them on
   * their own copy until hard-TTL expiry.
   *
   * <p>
   * A constant permanent {@link #hardTtl()} ({@code Long.MAX_VALUE}) combined
   * with {@code sync = true} is rejected at resolution, before the body runs; a
   * dynamic hard TTL that does not read {@code #result} is rejected before the
   * body as soon as it resolves to permanent. A result-dependent hard TTL is
   * only knowable after the body, so the facade rejects it at the write. The
   * same rule applies when no override is given but
   * {@code zeta.local.hard-ttl-ms=0} resolves the effective hard TTL to
   * permanent: the facade rejects the synced write instead of broadcasting an
   * entry peers can never expire.
   *
   * @return whether the write is synchronized across instances
   */
  boolean sync() default true;
}
